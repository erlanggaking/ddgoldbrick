export function useTranslation(lang: 'id' | 'en') {
  return translations[lang];
}

export function formatPrice(price: number, lang?: 'id' | 'en'): string {
  const language = lang || 'id';
  return new Intl.NumberFormat(language === 'id' ? 'id-ID' : 'en-US', {
    style: 'currency',
    currency: 'IDR',
    minimumFractionDigits: 0,
  }).format(price);
}